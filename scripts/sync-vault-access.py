#!/usr/bin/env python3
"""Bundle the canonical fallback in each independently installable skill."""

import argparse
from pathlib import Path


SKILLS = ('nexus', 'research-wiki', 'vault-query', 'vault-write', 'vault-index', 'vault-lint')
START = '<!-- vault-access:start -->'
END = '<!-- vault-access:end -->'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Report missing/stale bundles without writing')
    args = parser.parse_args()
    root = Path(__file__).resolve().parent.parent
    source = root / 'skills/vault-write/references/mcpvault.md'
    text = source.read_text()
    if text.count(START) != 1 or text.count(END) != 1:
        parser.error('Canonical protocol must contain exactly one start/end marker pair')
    section = text.split(START, 1)[1]
    if END not in section:
        parser.error('Canonical protocol end marker must follow its start marker')
    section = section.split(END, 1)[0].strip()
    if not section:
        parser.error('Canonical fallback section is empty')
    bundle = '<!-- Generated by scripts/sync-vault-access.py; edit the canonical mcpvault.md. -->\n\n' + section + '\n'
    stale = []
    for skill in SKILLS:
        target = root / 'skills' / skill / 'references/vault-access.md'
        if target.is_file() and target.read_text() == bundle:
            continue
        stale.append(str(target.relative_to(root)))
        if not args.check:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(bundle)
    if args.check and stale:
        print('Missing/stale vault access bundles:\n' + '\n'.join(stale))
        return 1
    print(f'Vault access bundles: {len(SKILLS)} current' if args.check else f'Updated {len(stale)} vault access bundles')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
